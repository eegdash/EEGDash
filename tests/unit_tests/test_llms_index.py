import importlib.util
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location(
    "llms_generator", ROOT / "docs/generate_llms_txt.py"
)
llms = importlib.util.module_from_spec(spec)
spec.loader.exec_module(llms)


def page(source, name, content):
    path = source / "api/dataset" / f"eegdash.dataset.{name}.rst"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return path


def test_classify_by_dataset_directive_not_filename(tmp_path):
    for name in ("DS001234", "nm000001", "OtherArchive_42"):
        page(tmp_path, name, f".. dataset-page:: {name}\n")
    for name in ("base", "dataset", "registry"):
        page(tmp_path, name, f".. automodule:: eegdash.dataset.{name}\n")
    page(tmp_path, "DSwrong", ".. dataset-page:: DSother\n")
    assert [name for name, _ in llms._discover_dataset_pages(tmp_path)] == [
        "DS001234",
        "OtherArchive_42",
        "nm000001",
    ]
    assert {name for name, _ in llms._discover_api_pages(tmp_path)} >= {
        "eegdash.dataset.base",
        "eegdash.dataset.dataset",
        "eegdash.dataset.registry",
    }


def test_custom_url_and_determinism(tmp_path):
    page(tmp_path, "base", ".. automodule:: eegdash.dataset.base\n")
    page(tmp_path, "nm000001", ".. dataset-page:: nm000001\n")
    output = tmp_path / "llms.txt"
    llms.build(tmp_path, output, "https://preview.example/v2/")
    first = output.read_bytes()
    assert b"https://eegdash.org" not in first
    assert b"https://preview.example/v2/api/dataset/eegdash.dataset.base.html" in first
    llms.build(tmp_path, output, "https://preview.example/v2/")
    assert output.read_bytes() == first


def test_budget_counts_only_listed_entries_and_signals_truncation(tmp_path):
    for i in range(1000):
        name = f"Archive_é_{i:04}"
        page(tmp_path, name, f".. dataset-page:: {name}\n")
    output = tmp_path / "llms.txt"
    size = llms.build(tmp_path, output)
    text = output.read_text()
    dataset_section = text.split("## Dataset pages", 1)[1]
    listed = len(re.findall(r"^- \[", dataset_section, re.M))
    assert 0 < listed < 1000
    assert f"(N={listed})" in dataset_section
    assert f"Showing {listed} of 1000" in dataset_section
    assert "truncated" in dataset_section.lower()
    assert size <= llms.SIZE_BUDGET


