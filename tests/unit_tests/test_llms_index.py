def test_curated_html_links_have_current_sources():
    links = re.findall(r"\{site\}/([^)>]+\.html)", llms.CURATED_HEADER)
    missing = []
    for link in links:
        relative = Path(link).with_suffix(".rst")
        if link.startswith("generated/auto_examples/"):
            example = link.removeprefix("generated/auto_examples/")
            if example == "index.html":
                continue
            exists = (ROOT / "examples" / Path(example).with_suffix(".py")).is_file()
        elif link == "api/dataset/eegdash.EEGDashDataset.html":
            continue  # generated by dataset_page.shells
        else:
            exists = (ROOT / "docs/source" / relative).is_file()
        if not exists:
            missing.append(link)
    assert missing == []


def test_sphinx_build_generates_index_after_shells_and_checks_links(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    (source / "conf.py").write_text(
        f"import sys\nsys.path.insert(0, {str(ROOT / 'docs')!r})\n"
        "extensions = ['generate_llms_txt']\n"
        "html_baseurl = 'https://preview.example/v2/'\n"
        "def shells(app):\n"
        "    from pathlib import Path\n"
        "    p = Path(app.srcdir) / 'api/dataset/eegdash.dataset.nm000001.rst'\n"
        "    p.parent.mkdir(parents=True, exist_ok=True)\n"
        "    p.write_text('Dataset\\n=======\\n\\n.. dataset-page:: nm000001\\n')\n"
        "def setup(app):\n"
        "    from docutils.parsers.rst import Directive\n"
        "    class Dataset(Directive):\n"
        "        required_arguments = 1\n"
        "        def run(self): return []\n"
        "    app.add_directive('dataset-page', Dataset)\n"
        "    app.connect('builder-inited', shells)\n"
    )
    # Minimal stand-ins for all curated HTML/assets, not real data or network.
    for link in re.findall(r"\{site\}/([^)>]+)", llms.CURATED_HEADER):
        if link.endswith(".html"):
            path = source / Path(link).with_suffix(".rst")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("Page\n====\n")
        else:
            path = source / "_extra" / link
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("fixture")
    with (source / "conf.py").open("a") as f:
        f.write("html_extra_path = ['_extra']\n")
    output = tmp_path / "html"
    result = subprocess.run(
        [sys.executable, "-m", "sphinx", "-b", "html", str(source), str(output)],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    text = (output / "llms.txt").read_text()
    assert "Dataset pages (N=1)" in text
    assert (
        "https://preview.example/v2/api/dataset/eegdash.dataset.nm000001.html" in text
    )
    llms.validate_links(output / "llms.txt", output, "https://preview.example/v2/")
    (output / "install/install_pip.html").unlink()
    with pytest.raises(ValueError, match="install/install_pip.html"):
        llms.validate_links(output / "llms.txt", output, "https://preview.example/v2/")
